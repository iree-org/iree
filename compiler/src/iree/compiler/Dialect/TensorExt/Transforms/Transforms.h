#ifndef IREE_COMPILER_DIALECT_TENSOREXT_TRANSFORMS_TRANSFORMS_H_
#define IREE_COMPILER_DIALECT_TENSOREXT_TRANSFORMS_TRANSFORMS_H_

#include "mlir/Pass/Pass.h"
#include "mlir/Transforms/DialectConversion.h"

namespace mlir::iree_compiler::IREE::TensorExt {

#define GEN_PASS_DECL_RESOLVESPARSEINTERFACEOPSPASS
#include "iree/compiler/Dialect/TensorExt/Transforms/Passes.h.inc"

// Pass creation function is generated by TableGen

/// Patterns to fold tensor.extract_slice/insert_slice with
/// iree_tensor_ext.dispatch.tensor.load/store. These patterns may not be
/// canonicalizers, since they might change the parallelism semantics in
/// non-obvious ways.
void populateTensorSliceOpWithDispatchTensorOpFoldingPatterns(
    RewritePatternSet &results, MLIRContext *context);

/// Patterns to rewrite operations that read from sparse tensors (e.g.,
/// vector.transfer_read) to use the SparseOpInterface's resolveRange method.
/// This includes both tensor and memref patterns.
void populateSparseInterfaceRewritePatterns(RewritePatternSet &patterns);

/// Patterns to resolve tensor.dim/memref.dim on cast_to_ragged_shape results
/// for non-ragged-column dimensions (e.g., the raggedRow dim resolves to
/// numRaggedRows).
void populateResolveDimOfCastToRaggedShapePatterns(RewritePatternSet &patterns);

}; // namespace mlir::iree_compiler::IREE::TensorExt

#endif // IREE_COMPILER_DIALECT_TENSOREXT_TRANSFORMS_TRANSFORMS_H_
